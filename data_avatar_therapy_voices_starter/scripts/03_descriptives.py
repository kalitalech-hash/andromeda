#!/usr/bin/env python3
"""Basic descriptive analyses of strictly selected A/B/C metadata corpus."""
from __future__ import annotations
import argparse,csv,json,collections,datetime as dt
from pathlib import Path

def write_csv(p,rows,fields):
    p.parent.mkdir(parents=True,exist_ok=True)
    with p.open('w',newline='',encoding='utf-8') as f:
        w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(rows)

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--input',default='outputs/qa/avatar01_full_strict_v05/analysis_corpus_ABC.csv');ap.add_argument('--output-dir',default='outputs/analyses/avatar01_full_strict_v05');a=ap.parse_args()
    with open(a.input,encoding='utf-8-sig',newline='') as f:rows=list(csv.DictReader(f))
    if any(r.get('qa_layer') not in {'A','B','C'} for r in rows):raise ValueError('Expected screened A/B/C only')
    out=Path(a.output_dir);out.mkdir(parents=True,exist_ok=True)
    jl=collections.Counter((r['journal'],r['qa_layer']) for r in rows)
    yl=collections.Counter((r['year'],r['qa_layer']) for r in rows)
    ty=collections.Counter((r['publication_type'],r['qa_layer']) for r in rows)
    write_csv(out/'journal_layer_counts.csv',[{'journal':j,'layer':l,'count':n} for (j,l),n in sorted(jl.items())],['journal','layer','count'])
    write_csv(out/'year_layer_counts.csv',[{'year':y,'layer':l,'count':n} for (y,l),n in sorted(yl.items())],['year','layer','count'])
    write_csv(out/'type_layer_counts.csv',[{'publication_type':t,'layer':l,'count':n} for (t,l),n in sorted(ty.items())],['publication_type','layer','count'])
    s={'schema_version':'strict_analyses_0.5','created_utc':dt.datetime.now(dt.timezone.utc).isoformat(),'n':len(rows),'layer_counts':dict(collections.Counter(r['qa_layer'] for r in rows)),'limitations':'Metadata-based descriptive counts; not systematic search or treatment efficacy assessment; categories generated by regex; page-capped acquisition.'}
    (out/'analysis_summary.json').write_text(json.dumps(s,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    (out/'methods_note.md').write_text('# Preliminary descriptive analyses\n\nCounts by journal, year, publication type, and provisional strict A/B/C layers. No semantic normalization, network model, or causal interpretation was attempted. Full thematic maps require additional review and the existing titles-plus-abstracts pipeline.\n',encoding='utf-8')
    print(json.dumps(s,ensure_ascii=False,indent=2))
if __name__=='__main__':main()
